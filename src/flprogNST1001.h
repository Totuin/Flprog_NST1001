#pragma once

#include <Arduino.h>
#include "flprogUtilites.h"
#include "RT_HW_BASE.h"

/**
 * @brief Счётчик импульсов цифрового датчика температуры NOVOSENSE NST1001.
 *
 * Измерение датчика представлено серией от 1 до 3201 импульса. Метод interrupt()
 * вызывается пользователем при каждом спаде сигнала DQ (FALLING).
 * По паузе между сериями (10 мс и более) законченная серия переносится в _raw.
 * Поэтому последнее измерение становится доступно только с началом следующей серии.
 *
 * ВНИМАНИЕ: импульсы имеют период порядка 5–11 мкс. Программный обработчик
 * прерывания способен пропускать их на медленных МК. Это необходимо проверить
 * на реальной плате; для надёжной работы может потребоваться аппаратный счётчик.
 */
class FLProgNST1001
{
public:
    /**
     * @param pin GPIO, подключённый к DQ датчика.
     * @param extPower true — внешний подтягивающий резистор (INPUT);
     *                 false — внутренняя подтяжка (INPUT_PULLUP).
     */
    FLProgNST1001(int16_t pin, bool extPower = false);

    /** @return номер внешнего прерывания для attachInterrupt(). */
    uint8_t interruptNumber() { return digitalPinToInterrupt(_pin); }

    /**
     * @return температура (°C) по последней завершённой серии импульсов.
     * Пока getRAW() == 0, действительного измерения ещё нет — не используйте
     * полученное значение как температуру датчика.
     */
    float getTemperature();

    /**
     * @return число импульсов предыдущей завершённой серии (0 до первого кадра).
     * На 8-битных AVR чтение 16-битного поля защищено от разрыва прерыванием.
     */
    uint16_t getRAW();

    /**
     * @brief Учитывает очередной импульс DQ; вызывать из ISR по FALLING.
     *
     * Не вызывает Serial, delay или динамического выделения памяти.
     */
    void interrupt();

protected:
    int16_t _pin = -1;
    uint8_t filterOrder = 11; // Резерв прежнего API (фильтрация здесь не реализована).
    volatile uint16_t _count = 0; // Импульсы текущей, ещё не завершённой серии.
    volatile uint16_t _raw = 0;   // Опубликованное измерение; меняется в ISR.
    uint32_t _lastInterruptTime = 0; // millis() последнего спада, только ISR.
};
